def export_event_plots(
    parquet_path: Path,
    events: pd.DataFrame,
    output_dir: Path,
    context_hours_override: float | None = None,
    plot_index_output: Path | None = DEFAULT_PLOT_INDEX_OUTPUT,
    dpi: int = 150,
) -> pd.DataFrame:
    """Export contextual plots for either event schema."""
    if "source" in events.columns:
        plot_results = export_mapping_window_event_plots(
            parquet_path,
            events,
            output_dir,
            context_days_override=context_hours_override,
            dpi=dpi,
        )
    else:
        plot_results = export_first_difference_event_plots(
            parquet_path,
            events,
            output_dir,
            context_hours_override=context_hours_override,
            dpi=dpi,
        )

    if plot_index_output is not None:
        write_plot_index_csv(plot_index_output, plot_results if not plot_results.empty else empty_plot_index_frame())
    return plot_results


