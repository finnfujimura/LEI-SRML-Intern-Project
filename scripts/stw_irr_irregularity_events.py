def export_first_difference_event_plots(
    parquet_path: Path,
    events: pd.DataFrame,
    output_dir: Path,
    context_hours_override: float | None = None,
    dpi: int = 150,
) -> pd.DataFrame:
    """Export one contextual PNG per legacy first-difference event."""
    if events.empty:
        return empty_plot_index_frame()

    output_dir.mkdir(parents=True, exist_ok=True)
    metric_frames = {
        metric: load_metric_frame(parquet_path, metric)
        for metric in sorted(events["metric"].unique())
    }
    results: list[dict[str, object]] = []

    for event in events.itertuples(index=False):
        metric_frame = metric_frames[event.metric]
        irr_column = f"{event.metric}_Irr"
        context_hours = context_hours_override if context_hours_override is not None else event.plot_context_hours
        context = pd.Timedelta(hours=context_hours)
        plot_start = pd.Timestamp(event.event_start) - context
        plot_end = pd.Timestamp(event.event_end) + context
        window = metric_frame.loc[
            (metric_frame["datetime"] >= plot_start) & (metric_frame["datetime"] <= plot_end),
            ["datetime", irr_column],
        ].copy()
        if window.empty:
            continue

        metric_dir = output_dir / event.metric.lower()
        metric_dir.mkdir(parents=True, exist_ok=True)
        output_path = metric_dir / f"{event.event_id}.png"

        fig, ax = plt.subplots(figsize=(14, 6))
        ax.plot(
            window["datetime"],
            window[irr_column],
            color=METRIC_CONFIG[event.metric]["color"],
            linewidth=0.8,
        )
        ax.axvspan(pd.Timestamp(event.event_start), pd.Timestamp(event.event_end), color="#d62728", alpha=0.18)
        ax.axvline(pd.Timestamp(event.peak_datetime), color="#d62728", linestyle="--", linewidth=1)
        ax.set_title(
            f"{event.event_id} | {event.metric} IRR irregularity\n"
            f"{pd.Timestamp(event.event_start)} to {pd.Timestamp(event.event_end)} | "
            f"peak Δ={event.peak_abs_delta:.1f}"
        )
        ax.set_xlabel("Datetime")
        ax.set_ylabel("IRR")
        ax.grid(alpha=0.25, linewidth=0.6)
        ax.margins(x=0)
        locator = mdates.AutoDateLocator()
        ax.xaxis.set_major_locator(locator)
        ax.xaxis.set_major_formatter(mdates.ConciseDateFormatter(locator))
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        fig.tight_layout()
        fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
        plt.close(fig)

        results.append(
            {
                "plot_label": getattr(event, "plot_label", event.event_id),
                "event_id": event.event_id,
                "plot_metric": event.metric,
                "plot_filename": output_path.name,
                "plot_path": output_path,
                "irregularity_start": pd.Timestamp(event.event_start),
                "irregularity_end": pd.Timestamp(event.event_end),
                "source": "first_difference",
                "rule": event.rule,
                "rows_plotted": len(window),
            }
        )

    return pd.DataFrame(results)


