def detect_metric_flagged_points(
    metric_frame: pd.DataFrame,
    metric: str,
    change_quantile: float,
    local_z_threshold: float,
    rolling_window: int,
) -> tuple[pd.DataFrame, float]:
    """Return flagged timestamps for one metric based on extreme first differences."""
    irr_column = f"{metric}_Irr"
    values = pd.to_numeric(metric_frame[irr_column], errors="coerce")
    previous_values = values.shift(1)
    signed_delta = values - previous_values
    abs_delta = signed_delta.abs()

    local_median = abs_delta.rolling(
        window=rolling_window,
        center=True,
        min_periods=min(rolling_window, ROLLING_MIN_PERIODS),
    ).median()
    local_mad = (abs_delta - local_median).abs().rolling(
        window=rolling_window,
        center=True,
        min_periods=min(rolling_window, ROLLING_MIN_PERIODS),
    ).median()
    denominator = local_mad * 1.4826
    local_z = (abs_delta - local_median).abs() / denominator

    quantile_threshold = float(abs_delta.dropna().quantile(change_quantile))
    abs_floor = METRIC_CONFIG[metric]["min_abs_delta"]
    effective_threshold = max(quantile_threshold, abs_floor)

    mask = (
        values.notna()
        & previous_values.notna()
        & denominator.gt(0)
        & local_z.ge(local_z_threshold)
        & abs_delta.ge(effective_threshold)
    )

    flagged = pd.DataFrame(
        {
            "datetime": metric_frame.loc[mask, "datetime"],
            "metric": metric,
            "irr_column": irr_column,
            "value": values.loc[mask],
            "previous_value": previous_values.loc[mask],
            "signed_delta": signed_delta.loc[mask],
            "abs_delta": abs_delta.loc[mask],
            "local_median_abs_delta": local_median.loc[mask],
            "local_mad_abs_delta": local_mad.loc[mask],
            "local_z": local_z.loc[mask],
            "change_threshold": effective_threshold,
            "change_quantile": change_quantile,
            "local_z_threshold": local_z_threshold,
        }
    ).reset_index(drop=True)

    return flagged, effective_threshold


def collapse_flagged_points_to_events(
    flagged_points: pd.DataFrame,
    metric: str,
    change_threshold: float,
    merge_gap_minutes: int,
    min_flagged_points: int,
    plot_context_hours: float,
) -> pd.DataFrame:
    """Merge nearby flagged timestamps into one irregularity event."""
    if flagged_points.empty:
        return pd.DataFrame(
            columns=[
                "event_id",
                "metric",
                "event_start",
                "event_end",
                "duration_minutes",
                "flagged_points",
                "peak_datetime",
                "peak_value",
                "peak_previous_value",
                "peak_signed_delta",
                "peak_abs_delta",
                "peak_local_z",
                "change_threshold",
                "merge_gap_minutes",
                "plot_context_hours",
                "plot_start",
                "plot_end",
                "rule",
            ]
        )

    flagged_points = flagged_points.sort_values("datetime").reset_index(drop=True)
    gap_breaks = flagged_points["datetime"].diff().gt(pd.Timedelta(minutes=merge_gap_minutes))
    event_group = gap_breaks.fillna(False).cumsum()
    plot_context = pd.Timedelta(hours=plot_context_hours)

    records: list[dict[str, object]] = []
    for _, group in flagged_points.groupby(event_group):
        if len(group) < min_flagged_points:
            continue

        peak_idx = group["abs_delta"].idxmax()
        peak_row = group.loc[peak_idx]
        event_start = pd.Timestamp(group["datetime"].min())
        event_end = pd.Timestamp(group["datetime"].max())
        duration_minutes = int((event_end - event_start) / pd.Timedelta(minutes=1)) + 1

        records.append(
            {
                "metric": metric,
                "event_start": event_start,
                "event_end": event_end,
                "duration_minutes": duration_minutes,
                "flagged_points": int(len(group)),
                "peak_datetime": pd.Timestamp(peak_row["datetime"]),
                "peak_value": float(peak_row["value"]),
                "peak_previous_value": float(peak_row["previous_value"]),
                "peak_signed_delta": float(peak_row["signed_delta"]),
                "peak_abs_delta": float(peak_row["abs_delta"]),
                "peak_local_z": float(peak_row["local_z"]),
                "change_threshold": float(change_threshold),
                "merge_gap_minutes": int(merge_gap_minutes),
                "plot_context_hours": float(plot_context_hours),
                "plot_start": event_start - plot_context,
                "plot_end": event_end + plot_context,
                "rule": "extreme_first_difference",
            }
        )

    if not records:
        return pd.DataFrame(
            columns=[
                "event_id",
                "metric",
                "event_start",
                "event_end",
                "duration_minutes",
                "flagged_points",
                "peak_datetime",
                "peak_value",
                "peak_previous_value",
                "peak_signed_delta",
                "peak_abs_delta",
                "peak_local_z",
                "change_threshold",
                "merge_gap_minutes",
                "plot_context_hours",
                "plot_start",
                "plot_end",
                "rule",
            ]
        )

    events = pd.DataFrame(records).sort_values(["event_start", "metric"]).reset_index(drop=True)
    return events[
        [
            "metric",
            "event_start",
            "event_end",
            "duration_minutes",
            "flagged_points",
            "peak_datetime",
            "peak_value",
            "peak_previous_value",
            "peak_signed_delta",
            "peak_abs_delta",
            "peak_local_z",
            "change_threshold",
            "merge_gap_minutes",
            "plot_context_hours",
            "plot_start",
            "plot_end",
            "rule",
        ]
    ]


def detect_first_difference_events(
    parquet_path: Path,
    change_quantile: float = DEFAULT_CHANGE_QUANTILE,
    local_z_threshold: float = DEFAULT_LOCAL_Z_THRESHOLD,
    rolling_window: int = DEFAULT_ROLLING_WINDOW,
    merge_gap_minutes: int = DEFAULT_MERGE_GAP_MINUTES,
    min_flagged_points: int = DEFAULT_MIN_FLAGGED_POINTS,
    plot_context_hours: float = DEFAULT_PLOT_CONTEXT_HOURS,
) -> pd.DataFrame:
    """Detect the legacy minute-to-minute first-difference events."""
    event_frames: list[pd.DataFrame] = []

    for metric in METRICS:
        metric_frame = load_metric_frame(parquet_path, metric)
        flagged_points, threshold = detect_metric_flagged_points(
            metric_frame,
            metric,
            change_quantile,
            local_z_threshold,
            rolling_window,
        )
        event_frames.append(
            collapse_flagged_points_to_events(
                flagged_points,
                metric,
                threshold,
                merge_gap_minutes,
                min_flagged_points,
                plot_context_hours,
            )
        )

    events = pd.concat(event_frames, ignore_index=True) if event_frames else pd.DataFrame()
    if events.empty:
        return events

    events = events.sort_values(["event_start", "metric"]).reset_index(drop=True)
    events["event_id"] = [
        f"{metric}_irr_event_{index:03d}"
        for metric, index in zip(events["metric"], range(1, len(events) + 1))
    ]
    events["plot_label"] = events["event_id"]
    return events


