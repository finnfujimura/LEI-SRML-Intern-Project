def load_metric_frame(parquet_path: Path, metric: str) -> pd.DataFrame:
    """Load one cleaned IRR metric from parquet."""
    irr_column = f"{metric}_Irr"
    frame = pd.read_parquet(parquet_path, columns=["datetime", irr_column]).copy()
    frame["datetime"] = pd.to_datetime(frame["datetime"], errors="coerce")
    frame[irr_column] = pd.to_numeric(frame[irr_column], errors="coerce")
    frame = frame.dropna(subset=["datetime"]).sort_values("datetime").reset_index(drop=True)
    if frame.empty:
        raise ValueError(f"No rows found for {metric} in {parquet_path}.")
    return frame


def load_irr_frame(parquet_path: Path) -> pd.DataFrame:
    """Load the irradiance columns needed for mapping-window detection."""
    frame = pd.read_parquet(parquet_path, columns=["datetime", *IRR_COLUMNS, "SZA"]).copy()
    frame["datetime"] = pd.to_datetime(frame["datetime"], errors="coerce")
    for column in [*IRR_COLUMNS, "SZA"]:
        frame[column] = pd.to_numeric(frame[column], errors="coerce")
    frame = frame.dropna(subset=["datetime"]).sort_values("datetime").reset_index(drop=True)
    if frame.empty:
        raise ValueError(f"No rows found in {parquet_path}.")
    return frame


def build_daily_summary(irr_frame: pd.DataFrame, daylight_min_irr: float) -> pd.DataFrame:
    """Aggregate the minute-level irradiance frame into day-level features."""
    daytime_mask = irr_frame[IRR_COLUMNS].fillna(0).max(axis=1).ge(daylight_min_irr)
    daylight = irr_frame.loc[daytime_mask, ["datetime", *IRR_COLUMNS, "SZA"]].copy()
    if daylight.empty:
        raise ValueError("No daytime irradiance rows were available to summarize.")

    daylight["date"] = daylight["datetime"].dt.normalize()
    daily = pd.DataFrame(index=pd.Index(sorted(daylight["date"].unique()), name="date"))

    grouped = daylight.groupby("date")
    for metric in METRICS:
        prefix = metric.lower()
        metric_group = grouped[f"{metric}_Irr"]
        daily[f"{prefix}_count"] = metric_group.count()
        daily[f"{prefix}_p95"] = metric_group.quantile(0.95)
        daily[f"{prefix}_max"] = metric_group.max()

    closure_mask = (
        daylight["SZA"].between(0, 89.5)
        & daylight[IRR_COLUMNS].notna().all(axis=1)
    )
    closure_frame = daylight.loc[closure_mask, ["date", *IRR_COLUMNS, "SZA"]].copy()
    if not closure_frame.empty:
        cos_zenith = np.cos(np.deg2rad(closure_frame["SZA"]))
        closure_component = closure_frame["DNI_Irr"] * cos_zenith + closure_frame["DHI_Irr"]
        closure_frame["closure_rel_err"] = (
            (closure_frame["GHI_Irr"] - closure_component).abs()
            / pd.concat([closure_frame["GHI_Irr"], closure_component], axis=1).max(axis=1).clip(lower=1.0)
        )
        closure_group = closure_frame.groupby("date")["closure_rel_err"]
        daily["closure_p95"] = closure_group.quantile(0.95)
        daily["closure_median"] = closure_group.median()
        daily["closure_count"] = closure_group.count()
    else:
        daily["closure_p95"] = np.nan
        daily["closure_median"] = np.nan
        daily["closure_count"] = 0

    daily["dni_to_ghi_p95"] = daily["dni_p95"] / daily["ghi_p95"].clip(lower=1.0)
    daily["dhi_to_ghi_p95"] = daily["dhi_p95"] / daily["ghi_p95"].clip(lower=1.0)
    daily["peak_irr_max"] = daily[[f"{metric.lower()}_max" for metric in METRICS]].max(axis=1, skipna=True)
    return daily.sort_index()


def build_mapping_periods(workbook_path: Path) -> list[dict[str, pd.Timestamp | None]]:
    """Return workbook mapping periods annotated with exact effective timestamps."""
    _, snapshots, _ = load_column_map_workbook(workbook_path)
    periods: list[dict[str, pd.Timestamp | None]] = []
    for index, snapshot in enumerate(snapshots):
        next_effective = (
            pd.Timestamp(snapshots[index + 1].effective_at)
            if index + 1 < len(snapshots)
            else None
        )
        periods.append(
            {
                "effective_at": pd.Timestamp(snapshot.effective_at),
                "start_date": pd.Timestamp(snapshot.effective_at).normalize(),
                "next_effective_at": next_effective,
                "end_date": (
                    next_effective.normalize() - pd.Timedelta(days=1)
                    if next_effective is not None
                    else None
                ),
            }
        )
    return periods


def mapping_period_for_date(
    periods: list[dict[str, pd.Timestamp | None]],
    date_value: pd.Timestamp,
) -> dict[str, pd.Timestamp | None] | None:
    """Return the workbook mapping period containing *date_value*."""
    if not periods:
        return None
    starts = [period["start_date"] for period in periods]
    period_index = bisect_right(starts, date_value.normalize()) - 1
    if period_index < 0:
        return None
    return periods[period_index]


def nearest_mapping_change(
    periods: list[dict[str, pd.Timestamp | None]],
    date_value: pd.Timestamp,
) -> pd.Timestamp | pd.NaT:
    """Return the closest workbook effective timestamp to *date_value*."""
    if not periods:
        return pd.NaT
    return min(
        (period["effective_at"] for period in periods),
        key=lambda effective_at: abs(effective_at - date_value),
    )


def _add_rule(
    rule_records: list[tuple[str, float]],
    rule_name: str,
    severity: float,
    affected_metrics: set[str],
    metrics_to_add: list[str],
) -> None:
    """Append one triggered rule and track the metrics it implicates."""
    rule_records.append((rule_name, float(severity)))
    affected_metrics.update(metrics_to_add)


def evaluate_daily_structural_flags(
    daily: pd.DataFrame,
    physical_max_irr: float,
    segment_closure_break_threshold: float,
    segment_closure_collapse_threshold: float,
) -> pd.DataFrame:
    """Evaluate day-level structural rules aimed at mapping mistakes."""
    records: list[dict[str, object]] = []

    for date_value, row in daily.iterrows():
        rule_records: list[tuple[str, float]] = []
        affected_metrics: set[str] = set()
        closure_available = bool(row.get("closure_count", 0) >= MIN_CLOSURE_POINTS and pd.notna(row.get("closure_p95")))

        max_metrics = [
            metric
            for metric in METRICS
            if pd.notna(row.get(f"{metric.lower()}_max")) and row[f"{metric.lower()}_max"] > physical_max_irr
        ]
        if max_metrics:
            severity = 8.0 + max(0.0, (float(row["peak_irr_max"]) - physical_max_irr) / 1000.0)
            _add_rule(rule_records, "irr_above_physical_limit", severity, affected_metrics, max_metrics)

        if closure_available and float(row["closure_p95"]) >= segment_closure_collapse_threshold:
            severity = 7.0 + (float(row["closure_p95"]) - segment_closure_collapse_threshold) * 10.0
            _add_rule(
                rule_records,
                "solar_closure_collapsed",
                severity,
                affected_metrics,
                list(METRICS),
            )

        if (
            closure_available
            and float(row["closure_p95"]) >= segment_closure_break_threshold
            and pd.notna(row.get("dni_p95"))
            and pd.notna(row.get("ghi_p95"))
            and float(row["dni_p95"]) >= 600.0
            and float(row["ghi_p95"]) <= 600.0
            and float(row["dni_to_ghi_p95"]) >= 1.45
        ):
            severity = 4.0 + (float(row["dni_to_ghi_p95"]) - 1.45) * 3.0
            _add_rule(
                rule_records,
                "ghi_suppressed_relative_to_dni",
                severity,
                affected_metrics,
                ["GHI", "DNI", "DHI"],
            )

        if (
            pd.notna(row.get("ghi_p95"))
            and pd.notna(row.get("dni_p95"))
            and pd.notna(row.get("dhi_p95"))
            and float(row["ghi_p95"]) >= 600.0
            and float(row["dni_p95"]) <= 25.0
            and float(row["dhi_p95"]) <= 25.0
            and float(row.get("dhi_count", 0)) >= MIN_CLOSURE_POINTS
        ):
            severity = 6.0 + (float(row["ghi_p95"]) - 600.0) / 250.0
            _add_rule(
                rule_records,
                "dni_dhi_flatline_during_high_ghi",
                severity,
                affected_metrics,
                ["DNI", "DHI", "GHI"],
            )

        if (
            closure_available
            and float(row["closure_p95"]) >= segment_closure_break_threshold
            and pd.notna(row.get("dhi_p95"))
            and pd.notna(row.get("ghi_p95"))
            and pd.notna(row.get("dni_p95"))
            and float(row["dhi_p95"]) >= max(float(row["ghi_p95"]) * 1.2, 600.0)
            and float(row["dni_p95"]) <= 100.0
        ):
            severity = 5.0 + max(0.0, float(row["dhi_to_ghi_p95"]) - 1.2) * 3.0
            _add_rule(
                rule_records,
                "dhi_dominates_global_balance",
                severity,
                affected_metrics,
                ["DHI", "GHI", "DNI"],
            )

        sorted_rules = [name for name, _ in sorted(rule_records, key=lambda item: (-item[1], item[0]))]
        score = float(sum(severity for _, severity in rule_records))
        records.append(
            {
                "date": date_value,
                "is_flagged": bool(rule_records),
                "score": score,
                "rule_count": len(rule_records),
                "primary_rule": sorted_rules[0] if sorted_rules else "",
                "rules": sorted_rules,
                "affected_metrics": sorted(affected_metrics),
            }
        )

    return pd.DataFrame(records).set_index("date").sort_index()


def build_event_record(
    event_start_date: pd.Timestamp,
    event_end_date: pd.Timestamp,
    daily: pd.DataFrame,
    daily_flags: pd.DataFrame,
    periods: list[dict[str, pd.Timestamp | None]],
    plot_context_days: float,
    source: str,
    override_rule: str | None = None,
    override_rules: list[str] | None = None,
    override_metrics: list[str] | None = None,
) -> dict[str, object]:
    """Build one event record covering a range of whole days."""
    window = daily.loc[event_start_date:event_end_date].copy()
    flag_window = daily_flags.loc[event_start_date:event_end_date].copy()
    if window.empty:
        raise ValueError("Cannot build an event record from an empty day window.")

    if not flag_window.empty and flag_window["score"].max() > 0:
        peak_date = pd.Timestamp(flag_window["score"].idxmax())
    else:
        peak_date = pd.Timestamp(window["peak_irr_max"].idxmax())

    peak_row = window.loc[peak_date]
    peak_flag = flag_window.loc[peak_date] if peak_date in flag_window.index else None

    all_rules = override_rules or sorted(
        {
            rule_name
            for rules in flag_window.get("rules", pd.Series(dtype=object))
            for rule_name in (rules or [])
        }
    )
    all_metrics = override_metrics or sorted(
        {
            metric
            for metrics in flag_window.get("affected_metrics", pd.Series(dtype=object))
            for metric in (metrics or [])
        }
    )
    primary_rule = override_rule or (
        str(peak_flag["primary_rule"])
        if peak_flag is not None and str(peak_flag["primary_rule"])
        else (all_rules[0] if all_rules else "mapping_window")
    )
    metric = all_metrics[0] if len(all_metrics) == 1 else "MULTI"

    mapping_period = mapping_period_for_date(periods, event_start_date)
    mapping_period_start = mapping_period["effective_at"] if mapping_period else pd.NaT
    mapping_period_end = mapping_period["next_effective_at"] if mapping_period else pd.NaT
    nearest_change = nearest_mapping_change(periods, event_start_date)

    plot_context = pd.Timedelta(days=float(plot_context_days))
    event_end_timestamp = event_end_date + pd.Timedelta(hours=23, minutes=59)
    duration_days = int((event_end_date - event_start_date).days) + 1
    flagged_days = int(flag_window["is_flagged"].sum()) if "is_flagged" in flag_window else 0

    return {
        "metric": metric,
        "affected_metrics": ",".join(all_metrics),
        "source": source,
        "event_start": event_start_date,
        "event_end": event_end_timestamp,
        "duration_days": duration_days,
        "duration_minutes": duration_days * 1440,
        "flagged_days": flagged_days,
        "peak_datetime": peak_date + pd.Timedelta(hours=12),
        "peak_score": float(peak_flag["score"]) if peak_flag is not None else float("nan"),
        "peak_rule_count": int(peak_flag["rule_count"]) if peak_flag is not None else 0,
        "peak_ghi_p95": float(peak_row["ghi_p95"]) if pd.notna(peak_row["ghi_p95"]) else float("nan"),
        "peak_dni_p95": float(peak_row["dni_p95"]) if pd.notna(peak_row["dni_p95"]) else float("nan"),
        "peak_dhi_p95": float(peak_row["dhi_p95"]) if pd.notna(peak_row["dhi_p95"]) else float("nan"),
        "peak_ghi_max": float(peak_row["ghi_max"]) if pd.notna(peak_row["ghi_max"]) else float("nan"),
        "peak_dni_max": float(peak_row["dni_max"]) if pd.notna(peak_row["dni_max"]) else float("nan"),
        "peak_dhi_max": float(peak_row["dhi_max"]) if pd.notna(peak_row["dhi_max"]) else float("nan"),
        "peak_closure_p95": float(peak_row["closure_p95"]) if pd.notna(peak_row["closure_p95"]) else float("nan"),
        "window_ghi_p95_median": float(window["ghi_p95"].median(skipna=True)) if not window.empty else float("nan"),
        "window_dni_p95_median": float(window["dni_p95"].median(skipna=True)) if not window.empty else float("nan"),
        "window_dhi_p95_median": float(window["dhi_p95"].median(skipna=True)) if not window.empty else float("nan"),
        "window_dni_to_ghi_median": float(window["dni_to_ghi_p95"].median(skipna=True)) if not window.empty else float("nan"),
        "window_dhi_to_ghi_median": float(window["dhi_to_ghi_p95"].median(skipna=True)) if not window.empty else float("nan"),
        "window_closure_p95_median": float(window["closure_p95"].median(skipna=True)) if not window.empty else float("nan"),
        "rule": primary_rule,
        "rules": ",".join(all_rules),
        "mapping_period_start": mapping_period_start,
        "mapping_period_end": mapping_period_end,
        "starts_near_mapping_change": bool(
            pd.notna(nearest_change)
            and abs(event_start_date - nearest_change.normalize()) <= pd.Timedelta(days=MAPPING_CHANGE_NEARBY_DAYS)
        ),
        "nearest_mapping_change": nearest_change,
        "plot_context_days": float(plot_context_days),
        "plot_start": event_start_date - plot_context,
        "plot_end": event_end_timestamp + plot_context,
    }


def detect_mapping_segment_events(
    daily: pd.DataFrame,
    daily_flags: pd.DataFrame,
    workbook_path: Path,
    segment_closure_break_threshold: float,
    segment_closure_collapse_threshold: float,
    plot_context_days: float,
) -> tuple[list[dict[str, object]], list[tuple[pd.Timestamp, pd.Timestamp]], list[dict[str, pd.Timestamp | None]]]:
    """Detect long abnormal windows aligned with workbook mapping periods."""
    periods = build_mapping_periods(workbook_path)
    events: list[dict[str, object]] = []
    occupied_ranges: list[tuple[pd.Timestamp, pd.Timestamp]] = []

    for period in periods:
        start_date = pd.Timestamp(period["start_date"])
        end_date = pd.Timestamp(period["end_date"]) if period["end_date"] is not None else daily.index.max()
        segment = daily.loc[start_date:end_date]
        if segment.empty:
            continue

        closure_segment = segment.loc[segment["closure_count"].fillna(0) >= MIN_CLOSURE_POINTS]
        if closure_segment.empty:
            continue

        median_ghi_p95 = float(segment["ghi_p95"].median(skipna=True))
        median_dni_p95 = float(segment["dni_p95"].median(skipna=True))
        median_dhi_p95 = float(segment["dhi_p95"].median(skipna=True))
        median_dni_to_ghi = float(segment["dni_to_ghi_p95"].median(skipna=True))
        median_closure_p95 = float(closure_segment["closure_p95"].median(skipna=True))

        rule_name: str | None = None
        rule_list: list[str] = []
        metrics: list[str] = []

        if (
            median_closure_p95 >= segment_closure_collapse_threshold
            and median_ghi_p95 >= 200.0
            and median_dni_p95 <= 25.0
            and median_dhi_p95 <= 25.0
        ):
            rule_name = "mapping_segment_secondary_channels_flatline"
            rule_list = ["solar_closure_collapsed", "dni_dhi_flatline_during_high_ghi"]
            metrics = ["GHI", "DNI", "DHI"]
        elif (
            median_closure_p95 >= segment_closure_break_threshold
            and median_dni_to_ghi >= 1.45
            and median_dni_p95 >= 600.0
            and median_ghi_p95 <= 600.0
        ):
            rule_name = "mapping_segment_ghi_suppressed"
            rule_list = ["ghi_suppressed_relative_to_dni"]
            metrics = ["GHI", "DNI", "DHI"]

        if not rule_name:
            continue

        events.append(
            build_event_record(
                start_date,
                end_date,
                daily,
                daily_flags,
                periods,
                plot_context_days,
                source="mapping_segment",
                override_rule=rule_name,
                override_rules=rule_list,
                override_metrics=metrics,
            )
        )
        occupied_ranges.append((start_date, end_date))

    return events, occupied_ranges, periods


def date_is_occupied(
    date_value: pd.Timestamp,
    occupied_ranges: list[tuple[pd.Timestamp, pd.Timestamp]],
) -> bool:
    """Return True when *date_value* falls inside an already-kept event window."""
    return any(start_date <= date_value <= end_date for start_date, end_date in occupied_ranges)


def detect_daily_severe_events(
    daily: pd.DataFrame,
    daily_flags: pd.DataFrame,
    periods: list[dict[str, pd.Timestamp | None]],
    occupied_ranges: list[tuple[pd.Timestamp, pd.Timestamp]],
    daily_merge_gap_days: int,
    daily_min_event_days: int,
    single_day_severe_score: float,
    plot_context_days: float,
) -> list[dict[str, object]]:
    """Detect severe one-off windows outside the abnormal mapping segments."""
    severe_rule_names = {
        "irr_above_physical_limit",
        "solar_closure_collapsed",
        "dhi_dominates_global_balance",
        "dni_dhi_flatline_during_high_ghi",
    }

    eligible = daily_flags[
        daily_flags["rules"].apply(lambda rules: any(rule_name in severe_rule_names for rule_name in (rules or [])))
    ].copy()
    if eligible.empty:
        return []

    eligible = eligible.loc[~eligible.index.to_series().apply(lambda date_value: date_is_occupied(date_value, occupied_ranges))]
    if eligible.empty:
        return []

    severe_dates = list(eligible.index.sort_values())
    groups: list[tuple[pd.Timestamp, pd.Timestamp]] = []
    start_date = previous_date = severe_dates[0]
    for date_value in severe_dates[1:]:
        if (date_value - previous_date).days <= daily_merge_gap_days:
            previous_date = date_value
            continue
        groups.append((start_date, previous_date))
        start_date = previous_date = date_value
    groups.append((start_date, previous_date))

    events: list[dict[str, object]] = []
    for start_date, end_date in groups:
        flag_window = daily_flags.loc[start_date:end_date]
        duration_days = int((end_date - start_date).days) + 1
        keep_event = duration_days >= daily_min_event_days or float(flag_window["score"].max()) >= single_day_severe_score
        if not keep_event:
            continue

        events.append(
            build_event_record(
                start_date,
                end_date,
                daily,
                daily_flags,
                periods,
                plot_context_days,
                source="daily_severe",
            )
        )

    return events


